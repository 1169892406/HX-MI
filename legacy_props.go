// lookupLegacyProps 查某型号的老协议属性表。型号别名/继承已在生成时展开，
// 所以这里是一次直查；查不到返回 nil = 该型号不是登记过的老协议设备。
func legacyPropsOf(model string) map[string]legacyProp {
	if model == "" {
		return nil
	}
	if p, ok := legacyPropTable[model]; ok {
		return p
	}
	/*
	 * 只容忍 `:1` 这种**冒号后缀**（云端 model 偶尔带 MIoT 版本号）。
	 * ⚠ 绝不能把裸数字后缀也剥掉：`chuangmi.plug.m3` 的 `3` 是**型号本身**的一部分，
	 * 剥掉就变成 `chuangmi.plug.m` —— 查不到表，指示灯/温度全丢（本轮测试抓到的真 bug）。
	 */
	if j := strings.LastIndex(model, ":"); j > 0 {
		if p, ok := legacyPropTable[model[:j]]; ok {
			return p
		}
	}
	return nil
}
